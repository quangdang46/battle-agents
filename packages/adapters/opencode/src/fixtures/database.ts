/** A v2 assistant turn with a tool call in it. */
export function assistantTurn(options: {
  readonly tools?: readonly ToolCallFixture[];
  readonly reasoning?: boolean;
  readonly answer?: string;
  readonly error?: string;
  readonly createdAt?: number;
  readonly completedAt?: number;
}): Record<string, unknown> {
  const content: Record<string, unknown>[] = [];
  if (options.reasoning === true) {
    content.push({
      type: 'reasoning',
      text: '',
      time: { created: options.createdAt ?? FIXTURE_EPOCH_MS },
    });
  }
  for (const tool of options.tools ?? []) {
    content.push({
      type: 'tool',
      id: tool.callId,
      name: tool.name,
      executed: false,
      state: {
        status: tool.status,
        input: tool.input,
        ...(tool.error === undefined ? {} : { error: tool.error }),
      },
      time: {
        created: tool.createdAt ?? FIXTURE_EPOCH_MS,
        ran: tool.createdAt ?? FIXTURE_EPOCH_MS,
        completed: tool.completedAt ?? (tool.createdAt ?? FIXTURE_EPOCH_MS) + 25,
      },
    });
  }
  if (options.answer !== undefined) content.push({ type: 'text', text: options.answer });
  return {
    agent: 'build',
    model: { id: 'model-1', providerID: 'opencode', variant: 'default' },
    content,
    time: {
      created: options.createdAt ?? FIXTURE_EPOCH_MS,
      completed: options.completedAt ?? FIXTURE_EPOCH_MS,
    },
    ...(options.error === undefined
      ? {}
      : { error: { name: 'ProviderError', message: options.error } }),
  };
}

export interface ToolCallFixture {
  readonly callId: string;
  readonly name: string;
  readonly input?: Record<string, unknown>;
  readonly status?: string;
  readonly error?: string;
  readonly createdAt?: number;
  readonly completedAt?: number;
}

/** A v1 tool part, whose call id lives on `callID` rather than on `id`. */
export function toolPart(call: ToolCallFixture): Record<string, unknown> {
  return {
    type: 'tool',
    callID: call.callId,
    tool: call.name,
    state: {
      status: call.status ?? 'completed',
      input: call.input ?? {},
      ...(call.error === undefined ? {} : { error: call.error }),
    },
  };
}

function normaliseColumn(value: unknown): string | number | null {
  if (value === undefined) return null;
  if (typeof value === 'boolean') return value ? 1 : 0;
  if (typeof value === 'string' || typeof value === 'number') return value;
  return JSON.stringify(value);
}
